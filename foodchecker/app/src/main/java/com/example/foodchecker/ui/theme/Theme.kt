@Immutable
data class VerdictColors(
    val safe: Color,
    val dangerous: Color,
    val unknown: Color
)

private val LightVerdictColors = VerdictColors(
    safe = VerdictSafeLight,
    dangerous = VerdictDangerousLight,
    unknown = VerdictUnknownLight
)

private val DarkVerdictColors = VerdictColors(
    safe = VerdictSafeDark,
    dangerous = VerdictDangerousDark,
    unknown = VerdictUnknownDark
)

private val LocalVerdictColors = staticCompositionLocalOf { LightVerdictColors }

@Composable
fun FoodCheckerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }
    val verdictColors = if (darkTheme) DarkVerdictColors else LightVerdictColors

    CompositionLocalProvider(LocalVerdictColors provides verdictColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AppTypography,
            shapes = AppShapes,
            content = content
        )
    }
}

object FoodCheckerTheme {
    val verdictColors: VerdictColors
        @Composable
        @ReadOnlyComposable
        get() = LocalVerdictColors.current
}
